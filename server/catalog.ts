function source(type: SourceType, label: string, config: Record<string, string>): CatalogSource {
  return { type, label, enabled: true, config };
}

function toCatalogItem(entry: Entry): CatalogItem {
  const sources: CatalogSource[] = [];
  if (entry.endoflife) {
    sources.push(source('endoflife', 'endoflife.date', { product: entry.endoflife }));
  }
  if (entry.repo) {
    sources.push(source('github_releases', 'GitHub Releases', { repo: entry.repo }));
  }
  if (entry.ghsa) {
    sources.push(
      source('github_advisories', 'GitHub Advisory', {
        package: entry.ghsa.package,
        ecosystem: entry.ghsa.ecosystem ?? '',
      }),
    );
  }
  if (entry.nvd) {
    sources.push(source('nvd', 'NVD CVE', { keyword: entry.nvd }));
  }
  sources.push(source('cisa_kev', 'CISA KEV', { feed: 'https://www.cisa.gov/sites/default/files/feeds/known_exploited_vulnerabilities.json' }));

  return {
    key: entry.key,
    name: entry.name,
    aliases: entry.aliases ?? [],
    category: entry.category,
    logoSlug: entry.logoSlug ?? null,
    website: entry.website ?? null,
    repo: entry.repo ? `https://github.com/${entry.repo}` : null,
    description: entry.description,
    watchLevel: entry.watchLevel ?? 'normal',
    sources,
  };
}

export const catalog: CatalogItem[] = entries.map(toCatalogItem);

export function findCatalogItem(key: string): CatalogItem | undefined {
  return catalog.find((item) => item.key === key);
}

export const categories = [...new Set(entries.map((entry) => entry.category))];
