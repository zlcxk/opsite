function source(type: SourceType, label: string, config: Record<string, string>): CatalogSource {
  return { type, label, enabled: true, config };
}

function coverageFor(sources: CatalogSource[]): CatalogCoverage {
  const has = (type: SourceType) => sources.some((item) => item.type === type);
  const lifecycle = has('endoflife');
  const releases = has('github_releases');
  const advisories = has('github_advisories') || has('nvd');
  const kev = has('cisa_kev');
  const notes: string[] = [];
  if (lifecycle) notes.push('生命周期');
  if (releases) notes.push('版本发布');
  if (has('github_advisories')) notes.push('GitHub 安全公告');
  const nvdSource = sources.find((item) => item.type === 'nvd');
  if (nvdSource) {
    notes.push(nvdSource.config.matchType === 'cpe' ? 'NVD 漏洞（CPE 精确匹配）' : 'NVD 漏洞（关键词匹配）');
  }
  if (kev) notes.push('KEV 交叉标记');
  const level =
    lifecycle && releases && advisories
      ? 'full'
      : (lifecycle || releases) && advisories
        ? 'partial'
        : 'limited';
  return { level, lifecycle, releases, advisories, kev, notes };
}

function toCatalogItem(entry: Entry): CatalogItem {
  const sources: CatalogSource[] = [];
  if (entry.endoflife) {
    sources.push(source('endoflife', 'endoflife.date', { product: entry.endoflife }));
  }
  if (entry.repo && (entry.releases ?? releasesVerified.has(entry.key))) {
    sources.push(source('github_releases', 'GitHub Releases', { repo: entry.repo }));
  }
  if (entry.ghsa) {
    sources.push(
      source('github_advisories', 'GitHub Advisory', {
        package: entry.ghsa.package,
        ecosystem: entry.ghsa.ecosystem ?? '',
      }),
    );
  }
  if (entry.nvd) {
    sources.push(
      source('nvd', 'NVD CVE', {
        keyword: entry.nvd,
        ...(entry.nvdCpe ? { cpeName: entry.nvdCpe } : {}),
        matchType: entry.nvdCpe ? 'cpe' : 'keyword',
        note: entry.nvdNote ?? (entry.nvdCpe ? 'CPE 精确匹配' : '关键词匹配，需人工核实边界'),
      }),
    );
  }
  sources.push(source('cisa_kev', 'CISA KEV', { feed: 'https://www.cisa.gov/sites/default/files/feeds/known_exploited_vulnerabilities.json' }));

  return {
    key: entry.key,
    name: entry.name,
    aliases: entry.aliases ?? [],
    tags: entry.tags ?? [],
    category: entry.category,
    logoSlug: entry.logoSlug ?? null,
    website: entry.website ?? null,
    repo: entry.repo ? `https://github.com/${entry.repo}` : null,
    description: entry.description,
    watchLevel: entry.watchLevel ?? 'normal',
    coverage: coverageFor(sources),
    sources,
  };
}

export const catalog: CatalogItem[] = entries.map(toCatalogItem);

export function findCatalogItem(key: string): CatalogItem | undefined {
  return catalog.find((item) => item.key === key);
}

export const categories = [...new Set(entries.map((entry) => entry.category))];
